(defmulti describe :kind)
(defmethod describe :dog [m] (str "dog named " (:name m)))
(defmethod describe :cat [m] (str "cat named " (:name m)))
(defmethod describe :default [m] (str "unknown " (:kind m)))
(println (describe {:kind :dog :name "rex"}))
(println (describe {:kind :cat :name "tom"}))
(println (describe {:kind :fish}))
(println (sort (keys (methods describe))))
